/**
 * build.mjs —— 日志包的编译脚本
 *
 * 只转译不打包：把包内 src/ 下每个 TS 文件一对一转成 dist/ 下的同名 JS；另跑 tsc --noEmit 只做类型检查。
 * 转译完成后再用 tsc（tsconfig.build.json）产出与 src 同形的 dist/*.d.ts（#27：纯 TS 包必须把类型一起发出去）。
 * 转译引擎优先用 esbuild（装了就用），本包依赖里没有 esbuild，于是自动回退 TypeScript 自带的
 * transpileModule（target ES2020 / module ESNext），两条路径语义等价；main 会打印实际用的引擎名。
 *
 * dist/ 是**入库**的构建产物（README「发布与产物」一节）：改了 src 必须重跑本脚本。
 * 「单测兜住 dist 过期」这句话不成立——测试跑的是 dist，过期了测试照样绿——所以 package.json 里
 * `pretest` 会先跑本脚本（`npm test` 一定在最新产物上跑）；只跑 `node --test` 时请自己先 build。
 *
 * 用法：node build.mjs（在包目录或仓库根目录均可）
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'
import { createRequire } from 'node:module'

const PKG_DIR = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(PKG_DIR, '..', '..')
const SRC_DIR = resolve(PKG_DIR, 'src')
const OUT_DIR = resolve(PKG_DIR, 'dist')

// 依赖解析（0.3.0 修）：本包可能在两种布局下被跑到——独立检出（依赖在 PKG_DIR/node_modules）
// 或 monorepo（依赖在仓库根 node_modules）。两条路径都试，谁有算谁，不再假定 ROOT 一定存在。
const REQUIRES = [createRequire(resolve(PKG_DIR, 'package.json')), createRequire(resolve(ROOT, 'package.json'))]

function requireFrom(args) {
  let lastError = null
  for (const req of REQUIRES) {
    try {
      return req(args)
    } catch (e) {
      lastError = e
    }
  }
  return null
}

// 路径解析（找 tsc 可执行文件用）：require.resolve 给路径字符串，与 requireFrom 的「加载模块」分开。
function resolveFrom(args) {
  for (const req of REQUIRES) {
    try {
      return req.resolve(args)
    } catch (e) {
      void e
    }
  }
  return null
}

// 转译单元＝src/ 下所有 .ts（递归，含子目录；.d.ts 只给类型检查、不产出 JS）。
// 0.3.0 起源码分了层（core/ 领域层、platform/ 端口层…），所以这里不能再写死文件清单：
// 收集是确定性的（字典序），dist/ 的产物路径与 src/ 的相对路径一一对应。
function collectUnits(dir, prefix) {
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    const rel = prefix ? prefix + '/' + entry.name : entry.name
    if (entry.isDirectory()) {
      out.push(...collectUnits(resolve(dir, entry.name), rel))
    } else if (entry.isFile() && entry.name.endsWith('.ts') && !entry.name.endsWith('.d.ts')) {
      out.push({ ts: rel, js: rel.slice(0, -3) + '.js' })
    }
  }
  return out
}

function headerFor(tsName) {
  return `// AUTO-GENERATED by build.mjs — DO NOT EDIT. Source: src/${tsName}\n`
}

/** 与门禁同一口径：转译加包头，换行归一，末尾恰好一个换行。 */
export function transpileUnit(tsName) {
  const tsPath = resolve(SRC_DIR, tsName)
  let source = readFileSync(tsPath, 'utf8')
  // 可执行入口（package.json 的 bin）的 shebang 必须是文件**第一行**：转译器把它当注释留在原位，
  // 而我们要在它前面加 AUTO-GENERATED 包头，所以先自己摘下来、转译后再放回最前面。
  // （BOM 也要摘：带 BOM 时 startsWith('#!') 是 false，shebang 会被当成非法 token。）
  if (source.charCodeAt(0) === 0xfeff) source = source.slice(1)
  let shebang = ''
  if (source.startsWith('#!')) {
    const nl = source.indexOf('\n')
    shebang = (nl > 0 ? source.slice(0, nl) : source) + '\n'
    source = nl > 0 ? source.slice(nl + 1) : ''
  }
  const body = loadEngine().transform(source).replace(/\r\n/g, '\n').replace(/\s+$/, '') + '\n'
  return shebang + headerFor(tsName) + body
}

// ---- 转译引擎（0.3.0 修）：优先 esbuild（与历史产物同源），缺失则回退 TypeScript 自带转译器。 ----
// 为什么允许回退：本包可能在独立检出下构建，而 esbuild 只是历史构建依赖、并非运行时依赖；
// 构建步骤不该因为没有它而整条断掉。两个引擎在「ts 输入 / esm 输出 / es2020 目标」下语义等价
// （差异只在数字字面量与引号风格这类源码形态，测试与门禁都不据此断言）。
let engineCache = null

function loadEngine() {
  if (engineCache) return engineCache
  const esbuild = requireFrom('esbuild')
  if (esbuild && typeof esbuild.transformSync === 'function') {
    engineCache = {
      name: 'esbuild',
      transform: (source) => esbuild.transformSync(source, { loader: 'ts', format: 'esm', target: 'es2020' }).code
    }
    return engineCache
  }
  const ts = requireFrom('typescript')
  if (!ts) throw new Error('[dsh-log] 既找不到 esbuild 也找不到 typescript：请先在包目录或仓库根安装依赖')
  engineCache = {
    name: 'typescript',
    transform: (source) =>
      ts.transpileModule(source, {
        compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext },
        fileName: 'unit.ts'
      }).outputText
  }
  return engineCache
}

function runTypeCheck() {
  const tsPkgPath = resolveFrom('typescript/package.json')
  if (!tsPkgPath) {
    throw new Error('[dsh-log] 找不到 typescript：请先在包目录或仓库根安装依赖（devDependencies 含 typescript）')
  }
  const tscBin = resolve(dirname(tsPkgPath), 'bin/tsc')
  const r = spawnSync(process.execPath, [tscBin, '-p', resolve(PKG_DIR, 'tsconfig.json')], {
    encoding: 'utf8'
  })
  if (r.status !== 0) {
    throw new Error(`[dsh-log] tsc --noEmit 未通过：\n${r.stdout || ''}${r.stderr || ''}`)
  }
  console.log('[dsh-log] tsc --noEmit 通过')
}

// 声明产出（#27 发行面）：转译器（esbuild / transpileModule）都只吐 JS、不出类型，
// 所以类型声明必须另跑一次 tsc（tsconfig.build.json，emitDeclarationOnly）。
// 为什么不让转译器顺手出：esbuild 不做类型检查，它生成的声明等于把源码形状猜一遍；
// 声明必须由真编译器产出，否则「有 .d.ts」只是看上去有。
function runDeclarations() {
  const tsPkgPath = resolveFrom('typescript/package.json')
  if (!tsPkgPath) {
    throw new Error('[dsh-log] 找不到 typescript：产出 .d.ts 需要它（devDependencies 含 typescript）')
  }
  const tscBin = resolve(dirname(tsPkgPath), 'bin/tsc')
  const r = spawnSync(process.execPath, [tscBin, '-p', resolve(PKG_DIR, 'tsconfig.build.json')], {
    encoding: 'utf8'
  })
  if (r.status !== 0) {
    throw new Error(`[dsh-log] tsc 产出声明未通过：\n${r.stdout || ''}${r.stderr || ''}`)
  }
  const declared = collectUnits(SRC_DIR, '').map((u) => u.ts.slice(0, -3) + '.d.ts')
  for (const d of declared) {
    if (!existsSync(resolve(OUT_DIR, d))) {
      throw new Error(`[dsh-log] 声明缺失：dist/${d}（tsconfig.build.json 的 rootDir/outDir 是否与 src 同形？）`)
    }
  }
  console.log(`[dsh-log] 类型声明：${declared.length} 个 .d.ts -> dist/`)
}

function main() {
  runTypeCheck()
  console.log(`[dsh-log] 转译引擎：${loadEngine().name}`)
  mkdirSync(OUT_DIR, { recursive: true })
  const units = collectUnits(SRC_DIR, '')
  for (const u of units) {
    const text = transpileUnit(u.ts)
    const outPath = resolve(OUT_DIR, u.js)
    mkdirSync(dirname(outPath), { recursive: true })
    writeFileSync(outPath, text, 'utf8')
    console.log(`[dsh-log] ${u.ts} -> dist/${u.js}（${text.split('\n').length} 行）`)
  }
  runDeclarations()
}

const invoked = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invoked) {
  try {
    main()
  } catch (e) {
    console.error((e && e.message) || e)
    process.exit(1)
  }
}
